  homepage "https://github.com/Jozef2J/tror"
  url "https://github.com/Jozef2J/tror/releases/download/v0.30.4/trorpad-linux-x86_64"
  version "0.30.4"
  sha256 "0b5ad5ecc59212675ffed7c0ebddd0de27efcf7fe8086f3523d968afc503ba8d"
  license any_of: ["MIT", "Apache-2.0"]

  depends_on arch: :x86_64
  depends_on :linux

  def install
    bin.install "trorpad-linux-x86_64" => "trorpad"
  end

  test do
    assert_path_exists bin/"trorpad"
  end
end
